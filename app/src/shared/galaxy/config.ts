/**
 * Galaxy generation configuration.
 *
 * Everything here is *static* — a single source of truth for star count,
 * spectral class weights, and the word lists that compose star names.
 * Changing any value below changes the galaxy, so:
 *   - These values live in code (not env vars) so the type system and
 *     tests can pin them down.
 *   - The golden-snapshot test in TASK-3 commits a fixture derived from
 *     these defaults, so a "harmless tweak" still fails loudly.
 *
 * If you do need to tweak the galaxy (e.g. for a content drop), update
 * the fixture in `__fixtures__/stars-dev-seed.json` and regenerate the
 * checksum — that is the only sanctioned change path.
 */

import type { SpectralClass } from "./types.js";

