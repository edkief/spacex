// ---------------------------------------------------------------------------
// Spectral class weights (probabilities)
// ---------------------------------------------------------------------------

/**
 * Probability of each spectral class for a newly drawn star.
 *
 * Real-world numbers (O ≈ 0.00003%, M ≈ 76%) would make O-class stars
 * literally never appear in a 200-star galaxy, so we compress the
 * distribution: rarer classes are bumped up a few orders of magnitude
 * so the player sees at least one of each class per galaxy, while
 * preserving the *ordering* (O < B < A < F < G < K < M). The gameplay
 * README (PRD §3) calls out that K and M are the "common" classes and
 * O/B are the rare, hand-painted highlights — these weights honour that.
 */
export const SPECTRAL_WEIGHTS: Readonly<Record<SpectralClass, number>> = {
  O: 0.005,
  B: 0.02,
  A: 0.05,
  F: 0.1,
  G: 0.18,
  K: 0.27,
  M: 0.375,
} as const;

/** Sum of weights must equal 1.0 — asserted by the test suite. */
export const SPECTRAL_WEIGHT_SUM = Object.values(SPECTRAL_WEIGHTS).reduce((a, b) => a + b, 0);

