/**
 * Postgres Drizzle schema for the Drift persistence layer.
 *
 * Twin of `./schema.sqlite.ts` for the production Postgres driver. The
 * table names and column names are byte-identical across drivers so the
 * repository code can stay driver-agnostic; only the type system and a
 * few native enums differ.
 *
 * Compilation-parity (TASK-62 AC2/3): this file should import without error
 * even when the sandbox has no live Postgres — `drizzle-kit generate`
 * accepts the schema purely from its TypeScript types.
 *
 * @see ./schema.sqlite.ts for the SQLite twin.
 */
import {
  boolean,
  check,
  index,
  integer,
  jsonb,
  pgEnum,
  pgTable,
  primaryKey,
  real,
  text,
  timestamp,
  uniqueIndex,
  uuid,
} from "drizzle-orm/pg-core";
import { sql } from "drizzle-orm";

/**
 * Strongly-typed enums for Postgres (no CHECK needed; the enum type is
 * enforced by the database). Equivalent SQLite tables use a CHECK
 * constraint (see schema.sqlite.ts).
 */
export const shipClassIdPg = pgEnum("ship_class_id", ["scout", "freighter", "interceptor"]);
export const shipStatePg = pgEnum("ship_state", ["docked", "flying", "onfoot", "destroyed"]);
export const shipRegimePg = pgEnum("ship_regime", ["space", "atmosphere", "surface"]);

/**
 * Player identity and starting state (PRD §8 / TASK-62 AC1, extended by TASK-34).
 *
 *   id             — UUID generated by Postgres (uuid_generate_v4 default).
 *   callsign       — player-chosen unique handle.
 *   credits        — server-controlled integer (default 500 per PRD).
 *   home_system_id — seed-derived system pointer.
 *   inventory      — JSONB `{stacks: {resourceId: amount}, weightUsed}` for
 *                    the on-foot backpack (TASK-34). NULL for pre-TASK-34
 *                    rows — the loader replaces NULL with an empty inventory.
 *   created_at     — wall-clock at first insert (timestamptz).
 *
 * Exported as a top-level binding so `drizzle-kit generate` can pick the
 * table up via AST inspection even when the module isn't fully evaluated.
 */
export const players = pgTable(
  "players",
  {
    id: uuid("id").primaryKey().defaultRandom().notNull(),
    callsign: text("callsign").notNull(),
    credits: integer("credits").notNull().default(500),
    homeSystemId: text("home_system_id"),
    inventory: jsonb("inventory"),
    createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
  },
  (t) => [uniqueIndex("players_callsign_unique").on(t.callsign)],
);

/**
 * Per-player ship state (TASK-24 adds flight persistence columns).
 *
 *   id                — UUID (Postgres defaults to uuid_generate_v4).
 *   owner_id          — FK → players.id (cascade delete).
 *   class_id          — typed enum (ship_class_id_pg).
 *   livery            — JSONB.
 *   hull              — REAL (percent).
 *   shields           — REAL (percent).
 *   position          — JSONB.
 *   velocity          — JSONB.
 *   state             — typed enum (ship_state_pg).
 *   quat              — JSONB orientation quaternion (TASK-24).
 *   regime            — typed enum (ship_regime_pg) | NULL (TASK-24).
 *   on_pad            — text | NULL — pad id when landed (TASK-24).
 *   wreck_expires_at  — timestamptz | NULL — GC for wrecks (TASK-24).
 *   cargo             — jsonb | NULL — persistent cargo hold (TASK-39).
 *                       Shape: `{stacks: {resourceId: amount}, weightUsed, capacity}`.
 *   updated_at        — timestamptz, bumped on every write.
 *
 * The four added columns mirror the SQLite migration
 * `0002_ship_state.sql` and were added directly to the schema so
 * compile-time parity holds — `drizzle-kit generate` will emit the
 * corresponding `ALTER TABLE` statements in the operator migration.
 */
export const ships = pgTable(
  "ships",
  {
    id: uuid("id").primaryKey().defaultRandom().notNull(),
    ownerId: uuid("owner_id")
      .notNull()
      .references(() => players.id, { onDelete: "cascade" }),
    classId: shipClassIdPg("class_id").notNull(),
    livery: jsonb("livery").notNull(),
    hull: real("hull").notNull(),
    shields: real("shields").notNull(),
    position: jsonb("position").notNull(),
    velocity: jsonb("velocity").notNull(),
    state: shipStatePg("state").notNull(),
    quat: jsonb("quat"),
    regime: shipRegimePg("regime"),
    onPad: text("on_pad"),
    wreckExpiresAt: timestamp("wreck_expires_at", { withTimezone: true }),
    // TASK-39: persistent cargo hold (jsonb).
    cargo: jsonb("cargo"),
    updatedAt: timestamp("updated_at", { withTimezone: true }).notNull().defaultNow(),
  },
  (t) => [
    index("ships_owner_id_idx").on(t.ownerId),
    check("ships_hull_range_check", sql`${t.hull} BETWEEN 0 AND 100`),
    check("ships_shields_range_check", sql`${t.shields} BETWEEN 0 AND 100`),
  ],
);

/**
 * Ship cargo manifest — one row per (ship, resource). Unique constraint
 * prevents duplicates; quantity updates are atomic `UPDATE`s.
 */
export const cargoItems = pgTable(
  "cargo_items",
  {
    id: uuid("id").primaryKey().defaultRandom().notNull(),
    shipId: uuid("ship_id")
      .notNull()
      .references(() => ships.id, { onDelete: "cascade" }),
    resourceType: text("resource_type").notNull(),
    quantity: integer("quantity").notNull(),
  },
  (t) => [
    uniqueIndex("cargo_items_ship_resource_unique").on(t.shipId, t.resourceType),
    index("cargo_items_ship_id_idx").on(t.shipId),
    check("cargo_items_quantity_check", sql`${t.quantity} >= 0`),
  ],
);

/**
 * Authenticated session — token_hash is HMAC(SESSION_SECRET, raw_token).
 * Raw tokens are never stored; revocation = DELETE by token_hash.
 */
export const sessions = pgTable(
  "sessions",
  {
    tokenHash: text("token_hash").primaryKey().notNull(),
    playerId: uuid("player_id")
      .notNull()
      .references(() => players.id, { onDelete: "cascade" }),
    systemId: text("system_id"),
    createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
    expiresAt: timestamp("expires_at", { withTimezone: true }).notNull(),
  },
  (t) => [
    index("sessions_player_id_idx").on(t.playerId),
    index("sessions_expires_at_idx").on(t.expiresAt),
  ],
);

/**
 * Persistent resource depletion — rows appear here lazily as players mine.
 *
 * `system_id` is denormalized so a system shard can scope
 * `listNodeStates(systemId)` without recomputing the seed chain.
 */
export const resourceNodeState = pgTable(
  "resource_node_state",
  {
    nodeId: text("node_id").primaryKey().notNull(),
    quantityRemaining: integer("quantity_remaining").notNull(),
    respawnAt: timestamp("respawn_at", { withTimezone: true }),
    systemId: text("system_id"),
  },
  (t) => [
    index("resource_node_state_system_id_idx").on(t.systemId),
    check("resource_node_state_quantity_check", sql`${t.quantityRemaining} >= 0`),
  ],
);

/**
 * In-process system shard registry.
 */
export const systemRegistry = pgTable("system_registry", {
  systemId: text("system_id").primaryKey().notNull(),
  name: text("name").notNull(),
  shardActive: boolean("shard_active").notNull(),
  lastActiveAt: timestamp("last_active_at", { withTimezone: true }).notNull().defaultNow(),
});

/**
 * Persistent deposit state — TASK-37. Mirrors the SQLite
 * `deposits` table; see the SQLite schema for the full design
 * notes. The Postgres twin uses `primaryKey` from
 * `drizzle-orm/pg-core` to mirror the composite PK.
 */
export const deposits = pgTable(
  "deposits",
  {
    id: text("id").notNull(),
    systemId: text("system_id").notNull(),
    planetId: text("planet_id").notNull(),
    pos: text("pos").notNull(),
    resourceId: text("resource_id").notNull(),
    remaining: integer("remaining").notNull(),
    discovered: boolean("discovered").notNull().default(false),
    depositSeq: integer("deposit_seq").notNull(),
  },
  (t) => [
    primaryKey({ columns: [t.systemId, t.depositSeq] }),
    index("deposits_planet_id_idx").on(t.planetId),
    index("deposits_system_id_idx").on(t.systemId),
    check("deposits_remaining_check", sql`${t.remaining} >= 0`),
  ],
);

/** Aggregated Postgres schema bundle. */
export const pgSchema = {
  players,
  ships,
  cargoItems,
  sessions,
  resourceNodeState,
  systemRegistry,
  deposits,
} as const;

export type PgSchema = typeof pgSchema;
