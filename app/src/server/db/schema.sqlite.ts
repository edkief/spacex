/**
 * SQLite Drizzle schema for the Drift persistence layer.
 *
 * Defines the six logical tables defined in PRD §8 using the better-sqlite3
 * driver. Where the SQLite type system diverges from Postgres (UUIDs, enums,
 * timestamps) we use the closest SQLite-native equivalent and let the
 * migration runner enforce real types (`TEXT` for UUIDs, `CHECK` for enums,
 * ISO-8601 `TEXT` for timestamps since SQLite has no native timestamp type).
 *
 * @see ./schema.pg.ts for the Postgres twin (kept shape-compatible).
 * @see ./migrations/sqlite/0001_init.sql for the runtime DDL applied on boot.
 */
import { check, index, integer, sqliteTable, text, uniqueIndex } from "drizzle-orm/sqlite-core";
import { sql } from "drizzle-orm";

/**
 * Player identity and starting state (PRD §8 / TASK-62 AC1).
 *
 *   id             — RFC 4122 UUID generated by the repository.
 *   callsign       — player-chosen unique handle (1..32 chars, enforced in repo).
 *   credits        — server-controlled integer (default 500 per PRD).
 *   home_system_id — seed-derived system pointer (TASK-4).
 *   created_at     — wall-clock at first insert (ISO-8601 TEXT).
 */
const players = sqliteTable(
  "players",
  {
    id: text("id").primaryKey().notNull(),
    callsign: text("callsign").notNull(),
    credits: integer("credits").notNull().default(500),
    homeSystemId: text("home_system_id"),
    createdAt: text("created_at")
      .notNull()
      .default(sql`(CURRENT_TIMESTAMP)`),
  },
  (t) => [uniqueIndex("players_callsign_unique").on(t.callsign)],
);

/**
 * Per-player ship state (PRD §8 / TASK-62 AC1).
 *
 *   id         — RFC 4122 UUID.
 *   owner_id   — FK → players.id.
 *   class_id   — scout | freighter | interceptor (CHECK constraint).
 *   livery     — JSON object (3-colour scheme).
 *   hull       — INTEGER percent [0..100].
 *   shields    — INTEGER percent [0..100].
 *   position   — JSON {systemId, x, y, z}.
 *   velocity   — JSON {x, y, z}.
 *   state      — docked | flying | onfoot | destroyed (CHECK constraint).
 *   updated_at — wall-clock at last write.
 */
const ships = sqliteTable(
  "ships",
  {
    id: text("id").primaryKey().notNull(),
    ownerId: text("owner_id")
      .notNull()
      .references(() => players.id, { onDelete: "cascade" }),
    classId: text("class_id").notNull(),
    livery: text("livery").notNull(),
    hull: integer("hull").notNull(),
    shields: integer("shields").notNull(),
    position: text("position").notNull(),
    velocity: text("velocity").notNull(),
    state: text("state").notNull(),
    updatedAt: text("updated_at")
      .notNull()
      .default(sql`(CURRENT_TIMESTAMP)`),
  },
  (t) => [
    check("ships_class_id_check", sql`${t.classId} IN ('scout','freighter','interceptor')`),
    check("ships_state_check", sql`${t.state} IN ('docked','flying','onfoot','destroyed')`),
    index("ships_owner_id_idx").on(t.ownerId),
  ],
);

/**
 * Ship cargo manifest — one row per (ship, resource). Unique constraint
 * on (ship_id, resource_type) means we never store duplicate lines; quantity
 * updates are atomic `UPDATE` against the existing row.
 */
const cargoItems = sqliteTable(
  "cargo_items",
  {
    id: text("id").primaryKey().notNull(),
    shipId: text("ship_id")
      .notNull()
      .references(() => ships.id, { onDelete: "cascade" }),
    resourceType: text("resource_type").notNull(),
    quantity: integer("quantity").notNull(),
  },
  (t) => [
    uniqueIndex("cargo_items_ship_resource_unique").on(t.shipId, t.resourceType),
    index("cargo_items_ship_id_idx").on(t.shipId),
  ],
);

/**
 * Authenticated session — token_hash is the HMAC(SESSION_SECRET, raw_token).
 * We never store the raw token; revocation = DELETE by token_hash.
 */
const sessions = sqliteTable(
  "sessions",
  {
    tokenHash: text("token_hash").primaryKey().notNull(),
    playerId: text("player_id")
      .notNull()
      .references(() => players.id, { onDelete: "cascade" }),
    systemId: text("system_id"),
    createdAt: text("created_at")
      .notNull()
      .default(sql`(CURRENT_TIMESTAMP)`),
    expiresAt: text("expires_at").notNull(),
  },
  (t) => [
    index("sessions_player_id_idx").on(t.playerId),
    index("sessions_expires_at_idx").on(t.expiresAt),
  ],
);

/**
 * Persistent resource depletion — node_id is derived from the seed so rows
 * appear here lazily as players mine a chunk. quantity_remaining = 0 is the
 * depleted state; respawn_at NULL means "available now".
 *
 * `system_id` is denormalized here so a system shard can scope
 * `listNodeStates(systemId)` without recomputing the seed chain. It is
 * nullable so existing rows preserved from a schema-downgrade don't break
 * reads; new writes always populate it.
 */
const resourceNodeState = sqliteTable(
  "resource_node_state",
  {
    nodeId: text("node_id").primaryKey().notNull(),
    quantityRemaining: integer("quantity_remaining").notNull(),
    respawnAt: text("respawn_at"),
    systemId: text("system_id"),
  },
  (t) => [index("resource_node_state_system_id_idx").on(t.systemId)],
);

/**
 * In-process system shard registry — every shard touched since boot has a
 * row. `shard_active` = true while the router holds the shard in memory;
 * `last_active_at` is bumped on every load/save point.
 */
const systemRegistry = sqliteTable("system_registry", {
  systemId: text("system_id").primaryKey().notNull(),
  name: text("name").notNull(),
  shardActive: integer("shard_active", { mode: "boolean" }).notNull(),
  lastActiveAt: text("last_active_at")
    .notNull()
    .default(sql`(CURRENT_TIMESTAMP)`),
});

/**
 * Aggregated SQLite schema bundle. The naming is stable across drivers
 * (`schema.players`, `schema.ships`, …) so the repository only depends on
 * this object shape, not on `dialect`.
 */
export const sqliteSchema = {
  players,
  ships,
  cargoItems,
  sessions,
  resourceNodeState,
  systemRegistry,
} as const;

export type SqliteSchema = typeof sqliteSchema;
